package com.coredex.altrender.build;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

import org.gradle.api.DefaultTask;
import org.gradle.api.GradleException;
import org.gradle.api.file.ConfigurableFileCollection;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.tasks.InputFiles;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.PathSensitive;
import org.gradle.api.tasks.PathSensitivity;
import org.gradle.api.tasks.TaskAction;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldNode;

/**
 * Writes {@code org/lwjgl/opengl/ContextCapabilities.java}: LWJGL2's capability object, with one public boolean per
 * public boolean field of LWJGL 3's {@code GLCapabilities} (the same {@code GL_*}/{@code OpenGLxx} names LWJGL2 used),
 * copied in its constructor. Game code reads these fields directly, so each must exist to link.
 */
public abstract class GenerateContextCapabilities extends DefaultTask {

	/** The lwjgl-opengl jar (other files are ignored). */
	@InputFiles
	@PathSensitive(PathSensitivity.NAME_ONLY)
	public abstract ConfigurableFileCollection getOpenglJar();

	@OutputDirectory
	public abstract DirectoryProperty getOutputDirectory();

	@TaskAction
	public void run() throws IOException {
		List<String> fields = null;
		for (var file : getOpenglJar().getFiles()) {
			try (ZipFile zip = new ZipFile(file)) {
				ZipEntry e = zip.getEntry("org/lwjgl/opengl/GLCapabilities.class");
				if (e == null) {
					continue;
				}
				try (InputStream is = zip.getInputStream(e)) {
					ClassNode node = new ClassNode();
					new ClassReader(is.readAllBytes()).accept(node, ClassReader.SKIP_CODE);
					fields = new ArrayList<>();
					for (FieldNode f : node.fields) {
						if ((f.access & Opcodes.ACC_PUBLIC) != 0 && (f.access & Opcodes.ACC_STATIC) == 0 && f.desc.equals("Z")) {
							fields.add(f.name);
						}
					}
				}
			}
		}
		if (fields == null || fields.isEmpty()) {
			throw new GradleException("GLCapabilities not found in " + getOpenglJar().getFiles());
		}
		StringBuilder src = new StringBuilder();
		src.append("/*\n * Generated by Altrender's build (build-logic GenerateContextCapabilities); do not edit.\n")
				.append(" * SPDX-License-Identifier: LGPL-3.0-only\n */\n")
				.append("package org.lwjgl.opengl;\n\n")
				.append("/** LWJGL2's capability flags, filled from LWJGL 3's {@link GLCapabilities} (").append(fields.size())
				.append(" flags). */\n")
				.append("public final class ContextCapabilities {\n\n");
		for (String f : fields) {
			src.append("\tpublic final boolean ").append(f).append(";\n");
		}
		src.append("\n\tContextCapabilities(GLCapabilities caps) {\n");
		for (String f : fields) {
			src.append("\t\tthis.").append(f).append(" = caps.").append(f).append(";\n");
		}
		src.append("\t}\n}\n");
		Path out = getOutputDirectory().get().getAsFile().toPath().resolve("org/lwjgl/opengl/ContextCapabilities.java");
		Files.createDirectories(out.getParent());
		Files.writeString(out, src.toString(), StandardCharsets.UTF_8);
		getLogger().info("ContextCapabilities: {} flags", fields.size());
	}
}
